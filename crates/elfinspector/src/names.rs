pub fn lookup<T: Copy + Ord>(table: &[(T, &'static str)], key: T) -> Option<&'static str> {
    table
        .binary_search_by_key(&key, |&(k, _)| k)
        .ok()
        .map(|i| table[i].1)
}

pub fn reloc_table(machine: u16) -> Option<&'static [(u32, &'static str)]> {
    match machine {
        crate::consts::EM_X86_64 => Some(RELOC_X86_64),
        crate::consts::EM_386 => Some(RELOC_386),
        crate::consts::EM_AARCH64 => Some(RELOC_AARCH64),
        crate::consts::EM_ARM => Some(RELOC_ARM),
        crate::consts::EM_RISCV => Some(RELOC_RISCV),
        _ => None,
    }
}

pub fn reloc_name(machine: u16, kind: u32) -> Option<&'static str> {
    lookup(reloc_table(machine)?, kind)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_sorted_unique() {
        fn check<T: Ord + std::fmt::Debug>(t: &[(T, &str)]) {
            assert!(t.windows(2).all(|w| w[0].0 < w[1].0), "{:?}", t.first());
        }
        check(MACHINES);
        check(SEGMENT_TYPES);
        check(SECTION_TYPES);
        check(DYNAMIC_TAGS);
        check(RELOC_X86_64);
        check(RELOC_386);
        check(RELOC_AARCH64);
        check(RELOC_ARM);
        check(RELOC_RISCV);
    }

    #[test]
    fn known_names() {
        assert_eq!(lookup(MACHINES, 62), Some("X86_64"));
        assert_eq!(lookup(MACHINES, 183), Some("AARCH64"));
        assert_eq!(lookup(SEGMENT_TYPES, 0x6474e551), Some("GNU_STACK"));
        assert_eq!(lookup(DYNAMIC_TAGS, 0x6ffffffb), Some("FLAGS_1"));
        assert_eq!(reloc_name(62, 7), Some("JUMP_SLOT"));
        assert_eq!(reloc_name(183, 1026), Some("JUMP_SLOT"));
        assert_eq!(reloc_name(183, 283), Some("CALL26"));
        assert_eq!(reloc_name(3, 1), Some("32"));
        assert_eq!(reloc_name(9999, 1), None);
    }
}
